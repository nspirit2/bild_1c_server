using BuildSystem.Infrastructure;
using Microsoft.Data.SqlClient;
using Microsoft.EntityFrameworkCore;
using Xunit;

namespace BuildSystem.IntegrationTests;

/// <summary>Discovery skips SQL tests unless the caller explicitly opts into isolated database creation.</summary>
public sealed class SqlServerFactAttribute : FactAttribute
{
    public SqlServerFactAttribute()
    {
        if (string.IsNullOrWhiteSpace(Environment.GetEnvironmentVariable(SqlServerTestDatabase.ConnectionVariable)) ||
            !string.Equals(Environment.GetEnvironmentVariable(SqlServerTestDatabase.OptInVariable), "true", StringComparison.OrdinalIgnoreCase))
            Skip = "SQL Server tests require BUILDSYSTEM_TEST_SQL (Initial Catalog=master) and explicit BUILDSYSTEM_TEST_SQL_ALLOW_CREATE=true; no SQL resources were created.";
    }
}

public sealed class SqlServerTestDatabase : IAsyncDisposable
{
    public const string ConnectionVariable = "BUILDSYSTEM_TEST_SQL";
    public const string OptInVariable = "BUILDSYSTEM_TEST_SQL_ALLOW_CREATE";
    private readonly string _masterConnectionString;
    private bool _created;
    private bool _disposed;

    private SqlServerTestDatabase(string masterConnectionString)
    {
        _masterConnectionString = masterConnectionString;
        DatabaseName = "bs_ci_metadata_" + Guid.NewGuid().ToString("N");
        ConnectionString = new SqlConnectionStringBuilder(masterConnectionString)
        {
            InitialCatalog = DatabaseName,
            Pooling = false
        }.ConnectionString;
    }

    public string DatabaseName { get; }
    public string ConnectionString { get; }

    public static bool TryGetMasterConnectionString(out string connectionString, out string reason)
    {
        connectionString = "";
        reason = $"SQL Server integration tests require {ConnectionVariable} (master connection) and {OptInVariable}=true; no SQL resources were created.";
        if (!string.Equals(Environment.GetEnvironmentVariable(OptInVariable), "true", StringComparison.OrdinalIgnoreCase))
            return false;
        var input = Environment.GetEnvironmentVariable(ConnectionVariable);
        if (string.IsNullOrWhiteSpace(input))
            return false;
        try
        {
            var builder = new SqlConnectionStringBuilder(input);
            if (string.IsNullOrWhiteSpace(builder.DataSource) ||
                !string.Equals(builder.InitialCatalog, "master", StringComparison.OrdinalIgnoreCase) ||
                !string.IsNullOrEmpty(builder.AttachDBFilename))
            {
                reason = $"{ConnectionVariable} must specify a SQL Server and Initial Catalog=master; attaching or targeting an existing database is forbidden.";
                return false;
            }
            connectionString = builder.ConnectionString;
            return true;
        }
        catch (ArgumentException)
        {
            reason = $"{ConnectionVariable} is not a valid SQL Server connection string.";
            return false;
        }
    }

    public static async Task<SqlServerTestDatabase> CreateAsync(CancellationToken cancellationToken = default)
    {
        if (!TryGetMasterConnectionString(out var master, out var reason))
            throw new InvalidOperationException(reason);
        var database = new SqlServerTestDatabase(master);
        await using var connection = new SqlConnection(master);
        await connection.OpenAsync(cancellationToken);
        await using var command = connection.CreateCommand();
        command.CommandText = $"CREATE DATABASE [{database.DatabaseName}]";
        await command.ExecuteNonQueryAsync(cancellationToken);
        database._created = true;
        return database;
    }

    public BuildSystemDbContext NewContext()
    {
        if (!_created || _disposed)
            throw new InvalidOperationException("The owned SQL test database is not active.");
        return new BuildSystemDbContext(new DbContextOptionsBuilder<BuildSystemDbContext>()
            .UseSqlServer(ConnectionString, sql => sql.EnableRetryOnFailure(3, TimeSpan.FromSeconds(5), new[] { 51001 })).Options);
    }

    public async Task ApplyMigrationsAsync(CancellationToken cancellationToken = default)
    {
        await using var context = NewContext();
        await context.Database.MigrateAsync(cancellationToken);
    }

    public async ValueTask DisposeAsync()
    {
        if (_disposed)
            return;
        _disposed = true;
        if (!_created)
            return;
        _created = false;
        await using var connection = new SqlConnection(_masterConnectionString);
        await connection.OpenAsync();
        await using var command = connection.CreateCommand();
        // Only the unique name generated by THIS instance after successful CREATE is eligible.
        // Never use EnsureDeleted against the supplied catalog.
        command.CommandText = $"IF DB_ID(N'{DatabaseName}') IS NOT NULL BEGIN ALTER DATABASE [{DatabaseName}] SET SINGLE_USER WITH ROLLBACK IMMEDIATE; DROP DATABASE [{DatabaseName}]; END";
        await command.ExecuteNonQueryAsync();
    }
}

public sealed class SqlServerMigrationTests
{
    [SqlServerFact]
    public async Task Migrations_apply_to_new_disposable_sql_server_database()
    {
        await using var database = await SqlServerTestDatabase.CreateAsync();
        await database.ApplyMigrationsAsync();
        await using var context = database.NewContext();
        Assert.True(await context.Database.CanConnectAsync());
        Assert.NotEmpty(await context.Database.GetAppliedMigrationsAsync());
    }
}
